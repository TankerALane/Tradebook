"""Build Tradebook/Data/RecipeVendors.lua from docs/research/recipe_vendors.json.

The research file records, per recipe the classic data says is sold by a vendor, which
vendors WoW Forever sources confirm (see docs/DATA.md, "Recipe vendors"). This script turns it
into the addon's data; re-run it after editing the research file:

    python -I scripts/build_recipe_vendors.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "research", "recipe_vendors.json")
OUT = os.path.join(ROOT, "Tradebook", "Data", "RecipeVendors.lua")

FACTIONS = {2586: "Azeroth Commerce Authority", 2587: "Durotar Supply and Logistics", 270: "Zandalar Tribe",
            576: "Timbermaw Hold", 609: "Cenarion Circle", 749: "Hydraxian Waterlords", 2740: "Kirin Tor",
            2787: "Earthen Ring"}
STANDING = {"Neutral": 3, "Friendly": 4, "Honored": 5, "Revered": 6, "Exalted": 7}

STATUS = {"vendor": None, "none": 3, "notYet": 1, "disputed": 2, "notInForever": 4}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ids(xs):
    return "{" + ",".join(str(x) for x in xs) + "}"


def main():
    data = json.load(open(SRC, encoding="utf-8"))["recipes"]
    all_ids = [r["recipeSpellID"] for r in data]
    dupes = sorted({i for i in all_ids if all_ids.count(i) > 1})
    if dupes:
        raise SystemExit("recipes listed twice in the research file: %s" % dupes)
    names, quest_names = {}, {}
    lines = []
    for r in sorted(data, key=lambda r: r["recipeSpellID"]):
        conf = sorted({v["npc"] for v in r["vendors"] if v["confirmed"]})
        unconf = sorted({v["npc"] for v in r["vendors"] if not v["confirmed"]} - set(conf))
        # Drops and quests only where no vendor sells it (the classic data keeps the rest).
        other = r["status"] != "vendor"
        drops = sorted({d["npc"] for d in r["drops"]}) if other else []
        quests = sorted({q["quest"] for q in r["quests"]}) if other else []
        for v in r["vendors"]:
            names[v["npc"]] = v["name"]
        for q in r["quests"] if other else []:
            if q.get("name"): quest_names[q["quest"]] = q["name"]
        for d in r["drops"] if other else []:
            if d.get("name"): names[d["npc"]] = d["name"]
        parts = []
        if r["status"] in ("vendor", "none") and not (conf or unconf or quests or drops or r.get("trainer")
                                                   or r.get("auto") or r.get("notes")) and r.get("set") == "deep":
            continue
        if conf: parts.append("v=" + ids(conf))
        if unconf: parts.append("u=" + ids(unconf))
        if drops: parts.append("d=" + ids(drops))
        if quests: parts.append("q=" + ids(quests))
        if STATUS[r["status"]]: parts.append("x=%d" % STATUS[r["status"]])
        # New Forever vendors: Merchant's Favor cost, supply camp standing, other reputation,
        # skill to learn.
        if r.get("favor"): parts.append("fv=%d" % r["favor"])
        if r.get("campStanding"): parts.append("cr=%d" % STANDING[r["campStanding"]])
        rf = r.get("reputation")
        if rf and rf.get("factionID") and rf.get("standing") in STANDING:
            parts.append("rf={%d,%d}" % (rf["factionID"], STANDING[rf["standing"]]))
        if r.get("requiredSkill"): parts.append("k=%d" % r["requiredSkill"])
        # Deep dive (2026-11-14): trainer, learned automatically, a note, a cost in another currency.
        if r.get("trainer"): parts.append("tr=1")
        if r.get("auto"): parts.append("a=1")
        if r.get("notes"): parts.append("nt=" + lua_str(" ".join(r["notes"])))
        if r.get("costText"): parts.append("ct=" + lua_str(r["costText"]))
        lines.append("[%d]={%s}, -- %s" % (r["recipeSpellID"], ",".join(parts), r["recipeName"]))
    # Droppers per recipe, with drop chances (docs/research/recipe_vendors.json "drops").
    drop_lines, zones = [], {}
    for rid, d in sorted(((int(k), v) for k, v in json.load(open(SRC, encoding="utf-8")).get("drops", {}).items())):
        parts = []
        rows = []
        for n in d.get("npcs", []):
            rows.append("{%d,%d,%d,%d,%d}" % (n["npc"], round(n["chance"] * 100), n["drops"], n["loots"],
                                             1 if n["confirmed"] else 0))
            if n.get("name"): names[n["npc"]] = n["name"]
            if n.get("zone"): zones[n["npc"]] = n["zone"]
        if rows: parts.append("n={" + ",".join(rows) + "}")
        if d.get("world"): parts.append("w={%d,%d,%d}" % tuple(d["world"]))
        if parts: drop_lines.append("[%d]={%s}," % (rid, ",".join(parts)))
    out = [
        "-- Data/RecipeVendors.lua",
        "-- PURE. GENERATED by scripts/build_recipe_vendors.py from docs/research/recipe_vendors.json.",
        "-- Do not hand-edit; edit the research file and re-run the script.",
        "--",
        "-- WoW Forever recipe vendors, replacing the classic vendor lists in Data/SourceData.lua for",
        "-- every recipe listed here (checked 2026-11-13 against QuestieDB's Forever data and Forever",
        "-- web sources; see docs/DATA.md). [recipeID] = {",
        "--   v = vendors confirmed by two sources, u = vendors from one source (unconfirmed),",
        "--   d = NPCs that drop the recipe, q = quests that reward it (QuestieDB Forever),",
        "--   fv = Merchant's Favor cost, cr = supply camp standing needed (Durotar Supply and",
        "--   Logistics / Azeroth Commerce Authority, by your faction), rf = { factionID, standing }",
        "--   other reputation (4 Friendly .. 7 Exalted), k = skill to learn (new Forever recipes),",
        "--   x = 1 the recipe item doesn't seem to be in Forever yet, 2 sources disagree,",
        "--       3 no vendor is known to sell it in Forever }",
        "",
        "local _, ns = ...",
        "",
        "ns.RecipeVendors = {",
    ] + lines + [
        "}",
        "",
        "-- Names of the NPCs above (English).",
        "ns.RecipeVendorNames = {",
    ] + ["[%d]=%s," % (k, lua_str(names[k])) for k in sorted(names) if names[k]] + [
        "}",
        "",
        "-- Who drops each recipe: [recipeID] = { n = { { npcID, chance x100, drops, loots, confirmed } }",
        "-- (top 5, highest chance first; drops/loots = recorded loot counts, 0 when unknown;",
        "-- confirmed = two sources), w = { minLevel, maxLevel, droppers } world drop }.",
        "ns.RecipeDrops = {",
    ] + drop_lines + [
        "}",
        "",
        "-- Main zone (area ID) of the droppers above, for when Questie isn't installed.",
        "ns.RecipeNpcZones = {",
    ] + ["[%d]=%d," % (k, zones[k]) for k in sorted(zones)] + [
        "}",
        "",
        "-- Names of the quests above (English), for when the game hasn't loaded them yet.",
        "ns.RecipeQuestNames = {",
    ] + ["[%d]=%s," % (k, lua_str(quest_names[k])) for k in sorted(quest_names)] + [
        "}",
        "",
        "-- Names of the reputations above (English).",
        "ns.RecipeFactionNames = {",
    ] + ["[%d]=%s," % (k, lua_str(FACTIONS[k])) for k in sorted(FACTIONS)] + ["}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote", OUT, len(lines), "recipes", len(names), "names")


if __name__ == "__main__":
    main()
