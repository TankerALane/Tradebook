"""Build Tradebook/Data/RecipeVendors.lua from docs/research/recipe_vendors.json.

The research file records, per recipe the classic data says is sold by a vendor, which
vendors WoW Forever sources confirm (see docs/DATA.md, "Recipe vendors"). This script turns it
into the addon's data; re-run it after editing the research file:

    python -I scripts/build_recipe_vendors.py
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "research", "recipe_vendors.json")
OUT = os.path.join(ROOT, "Tradebook", "Data", "RecipeVendors.lua")

STATUS = {"vendor": None, "none": 3, "notYet": 1, "disputed": 2}


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ids(xs):
    return "{" + ",".join(str(x) for x in xs) + "}"


def main():
    data = json.load(open(SRC, encoding="utf-8"))["recipes"]
    names = {}
    lines = []
    for r in sorted(data, key=lambda r: r["recipeSpellID"]):
        conf = sorted({v["npc"] for v in r["vendors"] if v["confirmed"]})
        unconf = sorted({v["npc"] for v in r["vendors"] if not v["confirmed"]} - set(conf))
        # Drops and quests only where no vendor sells it (the classic data keeps the rest).
        other = r["status"] != "vendor"
        drops = sorted({d["npc"] for d in r["drops"]}) if other else []
        quests = sorted({q["quest"] for q in r["quests"]}) if other else []
        for v in r["vendors"]:
            names[v["npc"]] = v["name"]
        for d in r["drops"] if other else []:
            if d.get("name"): names[d["npc"]] = d["name"]
        parts = []
        if conf: parts.append("v=" + ids(conf))
        if unconf: parts.append("u=" + ids(unconf))
        if drops: parts.append("d=" + ids(drops))
        if quests: parts.append("q=" + ids(quests))
        if STATUS[r["status"]]: parts.append("x=%d" % STATUS[r["status"]])
        lines.append("[%d]={%s}, -- %s" % (r["recipeSpellID"], ",".join(parts), r["recipeName"]))
    out = [
        "-- Data/RecipeVendors.lua",
        "-- PURE. GENERATED by scripts/build_recipe_vendors.py from docs/research/recipe_vendors.json.",
        "-- Do not hand-edit; edit the research file and re-run the script.",
        "--",
        "-- WoW Forever recipe vendors, replacing the classic vendor lists in Data/SourceData.lua for",
        "-- every recipe listed here (checked 2026-11-13 against QuestieDB's Forever data and Forever",
        "-- web sources; see docs/DATA.md). [recipeID] = {",
        "--   v = vendors confirmed by two sources, u = vendors from one source (unconfirmed),",
        "--   d = NPCs that drop the recipe, q = quests that reward it (QuestieDB Forever),",
        "--   x = 1 the recipe item doesn't seem to be in Forever yet, 2 sources disagree,",
        "--       3 no vendor is known to sell it in Forever }",
        "",
        "local _, ns = ...",
        "",
        "ns.RecipeVendors = {",
    ] + lines + [
        "}",
        "",
        "-- Names of the NPCs above (English).",
        "ns.RecipeVendorNames = {",
    ] + ["[%d]=%s," % (k, lua_str(names[k])) for k in sorted(names) if names[k]] + ["}", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote", OUT, len(lines), "recipes", len(names), "names")


if __name__ == "__main__":
    main()
