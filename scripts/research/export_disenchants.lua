-- scripts/research/export_disenchants.lua
-- "import npc data", disenchant part: write Tradebook/Data/CommunityDisenchants.lua from the
-- maintainer's SavedVariables: their own disenchants (TradebookDB.disenchants) plus what other
-- players shared in game (TradebookDB.heard.de), combined the way Tradebook does it in game
-- (Core/Disenchant.lua Disenchant.Combine: another player counts for a band only once 2+
-- players reported it). Only per-band totals are written: no player hashes, no item lists.
--
-- The SavedVariables totals are cumulative, so the file is regenerated from them each time
-- (never added to), and Tradebook takes, per band, whichever has more disenchants: this file
-- or what the player has recorded and heard (so nobody's own results count twice).
--
-- usage: luajit scripts/research/export_disenchants.lua <SavedVariables/Tradebook.lua>

local svPath = ...
assert(svPath, "usage: luajit scripts/research/export_disenchants.lua <SavedVariables/Tradebook.lua>")

local f = assert(loadfile(svPath))
local env = {}
setfenv(f, env)
f()
local db = assert(env.TradebookDB, "no TradebookDB in " .. svPath)

-- Load the addon's own Combine (pure) instead of re-implementing it.
local ns = { L = {}, Compat = {} }
assert(loadfile("Tradebook/Data/DisenchantBands.lua"))("Tradebook", ns)
assert(loadfile("Tradebook/Core/Disenchant.lua"))("Tradebook", ns)
assert(loadfile("Tradebook/Core/Net.lua"))("Tradebook", ns)
-- Your own disenchants passed back to you by other players aren't another player's.
ns.Net.ForgetMine(db.heard, db.characters)

local combined = ns.Disenchant.Combine(db.disenchants or {}, db.heard and db.heard.de or {})

local bands = {}
for band in pairs(combined) do bands[#bands + 1] = band end
table.sort(bands)

local out = {
    "-- Data/CommunityDisenchants.lua",
    "-- PURE. GENERATED by scripts/research/export_disenchants.lua (\"import npc data\"). Do not hand-edit.",
    "--",
    "-- What disenchants gave in WoW Forever, per Forever disenchant band (Data/DisenchantBands.lua),",
    "-- from Tradebook players' recorded disenchants (only bands 2+ players reported count other",
    "-- players). Per-band totals only: { n = disenchants, players = n, mats = { [itemID] =",
    "-- { t = times seen, q = total count, lo, hi } } }.",
    "",
    "local _, ns = ...",
    "",
    "ns.CommunityDisenchants = {",
}
local total = 0
for _, band in ipairs(bands) do
    local rec = combined[band]
    local mats = {}
    for id in pairs(rec.mats) do mats[#mats + 1] = id end
    table.sort(mats)
    local parts = {}
    for _, id in ipairs(mats) do
        local m = rec.mats[id]
        parts[#parts + 1] = ("[%d]={t=%d,q=%d,lo=%d,hi=%d}"):format(id, m.t, m.q, m.lo, m.hi)
    end
    out[#out + 1] = ("[%d]={n=%d,players=%d,mats={%s}},"):format(band, rec.n, rec.players, table.concat(parts, ","))
    total = total + rec.n
end
out[#out + 1] = "}"
out[#out + 1] = ""

local file = assert(io.open("Tradebook/Data/CommunityDisenchants.lua", "wb"))
file:write(table.concat(out, "\n"))
file:close()
io.stderr:write(("community disenchants: %d bands, %d disenchants\n"):format(#bands, total))
