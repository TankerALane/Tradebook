"""Regenerate Tradebook/Data/SkillLevels.lua from WoW Forever's own game data.

Downloads the SkillLineAbility table for a Forever build from wago.tools (newest build by
default), writes the skill-up thresholds Tradebook uses, and prints what changed.

    yellow from TrivialSkillLineRankLow, grey from TrivialSkillLineRankHigh,
    green from floor((low + high) / 2)   -- matched every colour the game reported in testing

usage: python -I scripts/update_game_data.py [build]      e.g. 1.60.1.70938
Writes a summary to $GITHUB_STEP_SUMMARY when run in GitHub Actions.
"""
import csv
import io
import json
import os
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Tradebook" / "Data" / "SkillLevels.lua"
TOC = ROOT / "Tradebook" / "Tradebook_Forever.toc"
PRODUCT = "wowf"
SKILL_LINES = {171, 164, 333, 202, 165, 197, 185, 129, 356, 182, 186, 393}
UA = {"User-Agent": "tradebook-data-updater"}


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read().decode("utf-8")


def latest_build():
    builds = json.loads(fetch("https://wago.tools/api/builds"))
    versions = [b["version"] for b in builds.get(PRODUCT, [])]
    if not versions:
        sys.exit("no %s builds listed on wago.tools" % PRODUCT)
    return versions[0]


def read_current():
    """Previous file's build and rows, for the change report."""
    if not OUT.exists():
        return None, {}
    text = OUT.read_text(encoding="utf-8")
    build = re.search(r'ns\.GameDataBuild = "([^"]+)"', text)
    rows = {int(m[0]): tuple(int(x) for x in m[1:]) for m in
            re.findall(r"^\[(\d+)\]=\{(\d+),(\d+),(\d+),(\d+)\},$", text, re.M)}
    return (build.group(1) if build else None), rows


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else latest_build()
    data = fetch("https://wago.tools/db2/SkillLineAbility/csv?build=%s" % build)
    rows = {}
    for row in csv.DictReader(io.StringIO(data)):
        skill = int(row["SkillLine"])
        low, high = int(row["TrivialSkillLineRankLow"]), int(row["TrivialSkillLineRankHigh"])
        if skill in SKILL_LINES and high > 0:
            rows[int(row["Spell"])] = (skill, low, (low + high) // 2, high)
    if len(rows) < 500:
        sys.exit("only %d rows for build %s; refusing to overwrite (download problem?)" % (len(rows), build))

    old_build, old = read_current()
    added = sorted(set(rows) - set(old))
    removed = sorted(set(old) - set(rows))
    changed = sorted(r for r in set(rows) & set(old) if rows[r] != old[r])

    out = [
        "-- Data/SkillLevels.lua",
        "-- PURE. GENERATED by scripts/update_game_data.py from WoW Forever's own SkillLineAbility",
        "-- table (via wago.tools). Do not hand-edit; re-run the script for a new build.",
        "--",
        "-- [recipeID] = { skillLine, yellow, green, grey }  (skill where each colour starts;",
        "-- orange until yellow). Checked against the game's own colours in testing.",
        "",
        "local _, ns = ...",
        "",
        'ns.GameDataBuild = "%s"' % build,
        "",
        "ns.RecipeLevels = {",
    ]
    out += ["[%d]={%d,%d,%d,%d}," % ((rid,) + rows[rid]) for rid in sorted(rows)]
    out += ["}", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")

    # Does the TOC interface still match the build's major.minor.patch (1.60.1 -> 16001)?
    toc_iface = re.search(r"^## Interface: (\d+)", TOC.read_text(encoding="utf-8"), re.M)
    a, b, c = (int(x) for x in build.split(".")[:3])
    expected_iface = a * 10000 + b * 100 + c
    iface_note = ""
    if toc_iface and int(toc_iface.group(1)) != expected_iface:
        iface_note = "TOC Interface is %s but build %s suggests %d: check the client and update the TOC." % (
            toc_iface.group(1), build, expected_iface)

    report = [
        "Forever build: %s (previous: %s)" % (build, old_build or "none"),
        "Recipes with skill-up thresholds: %d" % len(rows),
        "Added: %d, removed: %d, changed: %d" % (len(added), len(removed), len(changed)),
    ]
    for rid in changed[:25]:
        report.append("  changed %d: %s -> %s" % (rid, old[rid], rows[rid]))
    if iface_note:
        report.append(iface_note)
    print("\n".join(report))
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as f:
            f.write("\n".join(report) + "\n")


if __name__ == "__main__":
    main()
